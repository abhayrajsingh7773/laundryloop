export function generateTimeline(currentStatus: LaundryStatus, baseDateStr: string): TimelineStep[] {
  const statusOrder: LaundryStatus[] = ['received', 'sorting', 'washing', 'drying', 'ready_for_pickup', 'collected'];
  const currentIndex = statusOrder.indexOf(currentStatus);

  return STATUS_STEPS.map((step, idx) => {
    const isDone = idx < currentIndex;
    const isCurrent = idx === currentIndex;
    let timestamp = 'Pending';

    if (idx === 0) timestamp = '23 Oct 2026, 09:30 AM';
    else if (idx === 1 && idx <= currentIndex) timestamp = '23 Oct 2026, 11:15 AM';
    else if (idx === 2 && idx <= currentIndex) timestamp = '23 Oct 2026, 02:45 PM';
    else if (idx === 3 && idx <= currentIndex) timestamp = '24 Oct 2026, 10:00 AM';
    else if (idx === 4 && idx <= currentIndex) timestamp = '24 Oct 2026, 04:30 PM';
    else if (idx === 5 && idx <= currentIndex) timestamp = '25 Oct 2026, 11:00 AM';

    return {
      status: step.status,
      label: step.label,
      description: step.description,
      timestamp,
      isDone,
      isCurrent,
      updatedBy: idx <= currentIndex ? 'Central Counter Staff (Ramesh K.)' : undefined,
    };
  });
}

